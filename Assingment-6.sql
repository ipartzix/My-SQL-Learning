CREATE TABLE EMP (
    E_ID      NUMERIC(6) PRIMARY KEY,
    FNAME     VARCHAR(30) NOT NULL,
    LNAME     VARCHAR(30) NOT NULL,
    HIRE_DATE DATE NOT NULL,
    JOB_ID    VARCHAR(10) NOT NULL,
    SAL       NUMERIC(8,2) NOT NULL,
    DEPT_ID   NUMERIC(4) CHECK (DEPT_ID >= 10)
);

