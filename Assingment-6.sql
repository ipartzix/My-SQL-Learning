SELECT CASE YEAR(CURDATE())
    WHEN 2026 THEN 'Two Thousand Twenty Six'
    WHEN 2025 THEN 'Two Thousand Twenty Five'
    WHEN 2024 THEN 'Two Thousand Twenty Four'
