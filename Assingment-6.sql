SELECT * FROM EMP;

SELECT DEPT_ID, MIN(SAL) AS MIN_SALARY
FROM EMP
GROUP BY DEPT_ID
HAVING MIN(SAL) > 3000
ORDER BY MIN_SALARY DESC;

SELECT CONCAT(
    FNAME,
    ' whose designation is ',
    JOB_ID,
    ' gets ',
    SAL,
    ' but wants to earn ',
    3 * SAL,
    '.'
) AS DETAILS
FROM EMP;

SELECT CONCAT(
    E_ID, ', ',
    FNAME, ', ',
    LNAME, ', ',
    DATE_FORMAT(HIRE_DATE, '%d-%b-%y'), ', ',
    JOB_ID, ', ',
    SAL, ', ',
    DEPT_ID
) AS EMPLOYEE_DETAILS
FROM EMP;

SELECT CURDATE() AS TODAY;

SELECT
    E_ID AS EMPLOYEE_ID,
    DAY(HIRE_DATE) AS DAY_HIRED,
    YEAR(HIRE_DATE) AS YEAR_HIRED
FROM EMP;

SELECT
    CONCAT(FNAME, ' ', LNAME) AS EMPLOYEE_NAME,
    DATE_FORMAT(HIRE_DATE, '%d-%M-%y') AS HIRE_DATE
FROM EMP;

SELECT
    E_ID AS EMPLOYEE_ID,
    MONTHNAME(HIRE_DATE) AS HIRE_MONTH
FROM EMP;

