CREATE TABLE INVOICE (
    INV_NO VARCHAR(3) PRIMARY KEY,
    MV_NO INT,
    CUST_ID VARCHAR(3),
    ISSUE_DATE DATE NOT NULL,
    RETURN_DATE DATE NOT NULL,
    CHECK (INV_NO LIKE 'I%'),
    FOREIGN KEY (MV_NO) REFERENCES MOVIE(MV_NO),
    FOREIGN KEY (CUST_ID) REFERENCES CUSTOMER(CUST_ID)
);

