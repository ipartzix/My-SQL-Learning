CREATE TABLE CUSTOMER (
    CUST_ID VARCHAR(3) PRIMARY KEY,
    FNAME VARCHAR(20) NOT NULL,
    LNAME VARCHAR(20),
    AREA VARCHAR(10),
    PHONE VARCHAR(15),
    CHECK (CUST_ID LIKE 'A%')
);

